function info(
  type: LicenseType,
  now: number,
  owner: { readonly name: string | undefined } = { name: 'ACME' },
  licenceKey: { readonly key: string | undefined } = { key: KEY },
): LicenseInfo {
  const fields: LicenseInfoFields = {
    type,
    generationDate: 0,
    expirationDate: EXPIRY,
    owner: owner.name,
    context: undefined,
    sha: undefined,
    key: licenceKey.key,
    currentTimeMillis: () => now,
  };
  return new LicenseInfo(fields);
}

