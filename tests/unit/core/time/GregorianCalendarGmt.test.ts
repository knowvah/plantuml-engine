describe('epochSecondsOfLenientDate (GregorianCalendar.set + getTimeInMillis)', () => {
  it.each(LENIENT_ROWS)('%i/%i/%i', (yyyy, mm, dd, seconds, monthDay) => {
    expect(epochSecondsOfLenientDate(yyyy, mm - 1, dd)).toBe(seconds);
    expect(monthDayOfEpochSeconds(seconds)).toBe(monthDay);
  });
});

describe('monthDayOfEpochSeconds across the 1582 cutover', () => {
  it.each([
    [-12_219_292_800, '10/15'],
    [-12_219_292_801, '10/04'],
    [-12_219_552_000, '10/02'],
    [0, '01/01'],
    [4530, '01/01'],
    [-1, '12/31'],
    [-63_072_000_000, '05/03'],
    [94_608_000_000, '01/04'],
  ])('%i -> %s', (seconds, monthDay) => {
    expect(monthDayOfEpochSeconds(seconds)).toBe(monthDay);
  });
});
