/** `jlm_cmmi10` ligature glyphs: code -> [width, height, depth, italic] (`<Char>` of each `ligCode`). */
const CMMI10_LIG_GLYPHS: Readonly<Record<number, readonly number[]>> = {};

/** `CharFont`: a glyph's font and code, what the kern and ligature tables are keyed by. */
export interface CharFont {
  font: 'jlm_cmr10' | 'jlm_cmmi10';
  code: number;
}

interface FontTables {
  kerns: Readonly<Record<number, readonly number[]>>;
  ligs: Readonly<Record<number, readonly number[]>>;
  ligGlyphs: Readonly<Record<number, readonly number[]>>;
}

const FONTS: Readonly<Record<CharFont['font'], FontTables>> = {
  jlm_cmr10: { kerns: CMR10_KERNS, ligs: CMR10_LIGS, ligGlyphs: CMR10_LIG_GLYPHS },
  jlm_cmmi10: { kerns: CMMI10_KERNS, ligs: CMMI10_LIGS, ligGlyphs: CMMI10_LIG_GLYPHS },
};

/** The value paired with `right` in a flat `[right, value, ...]` list. */
function pairValue(list: readonly number[] | undefined, right: number): number | undefined {
  if (list === undefined) return undefined;
  for (let i = 0; i + 1 < list.length; i += 2) if (list[i] === right) return list[i + 1];
  return undefined;
}

/** `DefaultTeXFont#getKern`: 0 across two fonts, else the table value
 *  scaled by the style's size factor (`PIXELS_PER_POINT` is 1). */
export function kernBetween(left: CharFont, right: CharFont, factor: number): number {
  if (left.font !== right.font) return 0;
  return (pairValue(FONTS[left.font].kerns[left.code], right.code) ?? 0) * factor;
}

/** A ligature's `CharFont` and glyph metrics. */
export interface Ligature {
  cf: CharFont;
  glyph: Glyph;
}

/** `DefaultTeXFont#getLigature`: `undefined` across two fonts or with no entry. */
export function ligatureOf(left: CharFont, right: CharFont): Ligature | undefined {
  if (left.font !== right.font) return undefined;
  const tables = FONTS[left.font];
  const code = pairValue(tables.ligs[left.code], right.code);
  const m = code === undefined ? undefined : tables.ligGlyphs[code];
  if (code === undefined || m === undefined) return undefined;
  const [width = 0, height = 0, depth = 0, italic = 0] = m;
  return { cf: { font: left.font, code }, glyph: { width, height, depth, italic } };
}
