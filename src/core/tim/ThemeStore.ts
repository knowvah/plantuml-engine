/**
 * Theme packages: themes that core does not bundle, registered by the host.
 *
 * Upstream reads every bundled theme as a jar resource, `/themes/<file>`,
 * through `Stdlib.class.getResourceAsStream` (`ThemeUtils.java:128-139`), the
 * same resource channel as the stdlib. Issue #180's ruling keeps only the
 * MIT, Apache-2.0 and `_none_` themes in core; the rest ship in separate
 * packages (`@knowvah/plantuml-themes-unlicensed`, `@knowvah/plantuml-themes-gpl`)
 * that a host registers. A registered package is this port's form of those
 * jar resources, so its themes resolve as bundled ones do (`EaterTheme.ts`,
 * `loadBundledOrLocalTheme`).
 *
 * Registration composes with the {@link IncludeStore} exactly as stdlib
 * bundles do through `withStdlib` (`StdlibStore.ts`): {@link withThemes} wraps
 * a store, and every preprocess entry already forwards the one store it is
 * given, embedded `{{ }}` diagrams included.
 *
 * ADR: `plans/themes-opt-in-packages/decisions.md` D1 (seam), D2 (lookup
 * order), D3 (`help themes`), D4 (residue).
 *
 * @see ~/git/plantuml/src/main/java/net/sourceforge/plantuml/theme/ThemeUtils.java#loadBundledOrLocalTheme
 * @see StdlibStore.ts#withStdlib
 */
import type { ThemeOverride } from '../theme.js';
import type { IncludeStore } from './IncludeStore.js';

/** One packaged theme: the verbatim upstream `puml-theme-<name>.puml` text. */
export interface PackagedTheme {
  /** The theme file, verbatim, YAML header included. */
  readonly source: string;
  /**
   * The json-family colours an executed `!theme` does not reach yet
   * (`build-theme.ts`, decisions D4). GENERATED by `scripts/compile-themes.py`
   * in lockstep with core; its shape may change with any core release, which
   * is why the packages pin core as a peer dependency.
   */
  readonly residue?: ThemeOverride;
}

/** A set of packaged themes, as one npm package exports it. */
export interface ThemePackage {
  /** The npm package name, for diagnostics. */
  readonly name: string;
  /** The package's SPDX licence expression (or `SEE LICENSE IN LICENSE`). */
  readonly license: string;
  readonly themes: Readonly<Record<string, PackagedTheme>>;
}

/** The registered themes, looked up by theme name. */
export interface ThemeStore {
  getTheme(name: string): PackagedTheme | undefined;
  /** Every registered theme name, in registration order, de-duplicated. */
  themeNames(): readonly string[];
}

/**
 * Builds a {@link ThemeStore} from theme packages. A name in two packages
 * resolves to the FIRST package's theme, as `combineAssetStores` does.
 * Lookups go through a `Map` of own keys, so `constructor` and other prototype
 * members miss.
 */
export function themeStore(...packages: readonly ThemePackage[]): ThemeStore {
  const byName = new Map<string, PackagedTheme>();
  for (const pkg of packages)
    for (const name of Object.keys(pkg.themes)) if (!byName.has(name)) byName.set(name, pkg.themes[name]!);

  const names = [...byName.keys()];
  return {
    getTheme: (name: string): PackagedTheme | undefined => byName.get(name),
    themeNames: (): readonly string[] => names,
  };
}

/**
 * Combines an {@link IncludeStore} with a {@link ThemeStore}: `get`/`has` and
 * the `getPumlResource` stdlib seam delegate to `base`, and the packaged-theme
 * methods to `themes`. Composes with `withStdlib` in either order.
 */
export function withThemes(base: IncludeStore, themes: ThemeStore): IncludeStore {
  return {
    get: (path: string): string | undefined => base.get(path),
    has: (path: string): boolean => base.has(path),
    getPumlResource: (fullname: string): string | undefined => base.getPumlResource?.(fullname),
    getPackagedTheme: (name: string): PackagedTheme | undefined => themes.getTheme(name),
    packagedThemeNames: (): readonly string[] => themes.themeNames(),
  };
}
